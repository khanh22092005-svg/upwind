"""Embed Phu's static poses (assets/phu/*-static.svg) into packages/lesson-scene/src/phu.ts.

Run from the project root after updating the mascot files: python3 -I tools/embed_phu.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
POSES = {"squeeze": "phu-blow-squeeze", "focus": "phu-blow-focus", "wave": "phu-wave", "idle": "phu-idle"}

out = ["// Generated by tools/embed_phu.py from assets/phu/*-static.svg (UpWind mascot guide v1). Do not edit.",
       "export type PhuPose = " + " | ".join(json.dumps(k) for k in POSES) + ";",
       "export const PHU: Record<PhuPose, { svg: string; viewBox: [number, number, number, number] }> = {"]
for pose, name in POSES.items():
    svg = open(os.path.join(ROOT, "assets/phu", f"{name}-static.svg"), encoding="utf-8").read()
    svg = re.sub(r"<metadata>.*?</metadata>", "", svg, flags=re.S)
    svg = re.sub(r"<\?xml.*?\?>|<!--.*?-->", "", svg, flags=re.S).strip()
    # Keep ids unique when several poses share one document.
    ids = set(re.findall(r'\sid="([^"]+)"', svg))
    for old in ids:
        svg = re.sub(rf'(["#(]){re.escape(old)}(["#)])', lambda m: f"{m.group(1)}phu-{pose}-{old}{m.group(2)}", svg)
    view = [float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split()]
    svg = re.sub(r"<svg\b", f'<svg class="phu-svg" preserveAspectRatio="xMidYMid meet"', svg, count=1)
    out.append(f"  {pose}: {{ svg: {json.dumps(svg, ensure_ascii=False)}, viewBox: {json.dumps(view)} }},")
out.append("};")
open(os.path.join(ROOT, "packages/lesson-scene/src/phu.ts"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("embedded", ", ".join(POSES))
